// build.rs — rust-embed 嵌入 + dist 校验（ADR-07，D-02；无网络，不调 cargo）
use std::env;
use std::fs;
use std::path::PathBuf;

fn copy_tree(src: PathBuf, dst: PathBuf) -> usize {
    let mut n = 0;
    if src.is_dir() {
        if !dst.is_dir() && fs::create_dir_all(dst.clone()).is_err() {
            panic!("build.rs: 无法创建目录: {}", dst.display());
        }
        for entry in fs::read_dir(src).unwrap() {
            let p = entry.unwrap().path();
            let name = p.file_name().unwrap().to_owned();
            n += copy_tree(p, dst.join(name));
        }
    } else if src.is_file() {
        if fs::copy(src.clone(), dst.clone()).is_err() {
            panic!("build.rs: 无法复制文件: {}", src.display());
        }
        n += 1;
    }
    n
}

fn prune(path: PathBuf) {
    if path.is_dir() {
        if fs::remove_dir_all(path.clone()).is_err() {
            panic!("build.rs: 无法清理目录: {}", path.display());
        }
    } else if path.is_file() && fs::remove_file(path.clone()).is_err() {
        panic!("build.rs: 无法清理文件: {}", path.display());
    }
}

fn main() {
    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_string()));
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_else(|_| ".".to_string()));
    let embed_dir = out_dir.join("embed");

    let dist = manifest.join("frontend").join("dist");
    let fallback = manifest.join("static").join("fallback");

    let is_release = env::var("PROFILE").map(|p| p == "release").unwrap_or(false);

    let source: PathBuf = if dist.join("index.html").is_file() {
        dist
    } else if is_release {
        panic!("build.rs: [D-02] release 构建要求 frontend/dist/index.html，请先执行 npm --prefix frontend run build");
    } else {
        println!("cargo:warning=[D-02] frontend/dist 未构建，嵌入 static/fallback 占位页");
        fallback
    };

    prune(embed_dir.clone());
    let copied = copy_tree(source.clone(), embed_dir.clone());
    if copied == 0 {
        panic!("build.rs: 静态资源目录为空: {}", source.display());
    }

    let folder = embed_dir.display().to_string();
    if folder.contains('"') {
        panic!("build.rs: OUT_DIR 含引号，无法生成 #[folder]");
    }
    let code = format!(
        "// generated by build.rs (D-02)\n#[derive(rust_embed::Embed)]\n#[folder = \"{}\"]\npub struct EmbeddedAssets;\n",
        folder
    );
    let embed_rs = out_dir.join("embed.rs");
    if fs::write(embed_rs.clone(), code).is_err() {
        panic!("build.rs: 无法写入 {}", embed_rs.display());
    }

    println!("cargo:rerun-if-changed=frontend/dist");
    println!("cargo:rerun-if-changed=static/fallback");
    println!("cargo:rerun-if-changed=build.rs");
    println!(
        "cargo:info=[build.rs] 嵌入 {} ({} 文件) -> {}",
        source.display(),
        copied,
        embed_dir.display()
    );
}
